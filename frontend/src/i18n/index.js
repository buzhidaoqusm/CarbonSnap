const staticTextMaps = {
  en: new Map(staticTextPairs.map(([en, zh]) => [zh, en])),
  zh: new Map(staticTextPairs),
};

function setLocale(nextLocale) {
  locale.value = normalizeLocale(nextLocale);
  if (typeof window !== "undefined") {
    window.localStorage.setItem(STORAGE_KEY, locale.value);
    document.documentElement.lang = locale.value === "zh" ? "zh-CN" : "en";
  }
}

function toggleLocale() {
  setLocale(locale.value === "zh" ? "en" : "zh");
}

function t(key, replacements = {}) {
  const template = messages[locale.value]?.[key] ?? messages.en[key] ?? key;
  return Object.entries(replacements).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

function localeLabel(targetLocale) {
  return targetLocale === "zh" ? "中文" : "EN";
}

export function useI18n() {
  const isChinese = computed(() => locale.value === "zh");
  const nextLocale = computed(() => (locale.value === "zh" ? "en" : "zh"));

  return {
    locale: readonly(locale),
    isChinese,
    nextLocale,
    setLocale,
    toggleLocale,
    t,
    localeLabel,
  };
}

setLocale(locale.value);

function translateTextNode(node, dictionary) {
  const raw = node.nodeValue || "";
  const trimmed = raw.trim();
  const translated = dictionary.get(trimmed);
  if (!translated) {
    return;
  }
  node.nodeValue = raw.replace(trimmed, translated);
}

function translateElementAttributes(element, dictionary) {
  ["placeholder", "aria-label", "title", "alt"].forEach((attribute) => {
    const value = element.getAttribute?.(attribute);
    const translated = dictionary.get(String(value || "").trim());
    if (translated) {
      element.setAttribute(attribute, translated);
    }
  });
}

export function applyStaticLocale(root = document.body) {
  if (typeof document === "undefined" || !root) {
    return;
  }

  const dictionary = staticTextMaps[locale.value] || staticTextMaps.en;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let node = walker.currentNode;
  while (node) {
    const parentElement = node.parentElement;
    if (
      parentElement &&
      ["SCRIPT", "STYLE", "TEXTAREA", "INPUT"].includes(parentElement.tagName)
    ) {
      node = walker.nextNode();
      continue;
    }
    if (node.nodeType === Node.TEXT_NODE) {
      translateTextNode(node, dictionary);
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      translateElementAttributes(node, dictionary);
    }
    node = walker.nextNode();
  }
}
